import type { ChatStatus } from "ai";
import { CornerDownLeftIcon, Loader2Icon, SquareIcon, XIcon } from "lucide-react";
import type {
  ComponentProps,
  FormEvent,
  FormEventHandler,
  HTMLAttributes,
  KeyboardEventHandler,
  MouseEvent,
} from "react";
import { useCallback, useState } from "react";
import {
  InputGroup,
  InputGroupAddon,
  InputGroupButton,
  InputGroupTextarea,
} from "@rambleraptor/homestead-core/shared/components/ui/input-group";
import { cn } from "@rambleraptor/homestead-core/shared/lib/utils";

export interface PromptInputMessage {
  text: string;
}

export type PromptInputProps = Omit<HTMLAttributes<HTMLFormElement>, "onSubmit"> & {
  onSubmit: (message: PromptInputMessage, event: FormEvent<HTMLFormElement>) => void | Promise<void>;
};

export const PromptInput = ({ className, onSubmit, children, ...props }: PromptInputProps) => {
  const handleSubmit: FormEventHandler<HTMLFormElement> = useCallback(
    async (event) => {
      event.preventDefault();
      const form = event.currentTarget;
      const field = form.elements.namedItem("message");
      const text = field instanceof HTMLTextAreaElement ? field.value : "";

      // Clear straight away so typing during the send isn't lost to a late
      // reset; put the text back if the send fails, so it can be retried.
      form.reset();
      try {
        await onSubmit({ text }, event);
      } catch {
        if (field instanceof HTMLTextAreaElement && field.value === "") {
          field.value = text;
        }
      }
    },
    [onSubmit],
  );

  return (
    <form className={cn("w-full", className)} onSubmit={handleSubmit} {...props}>
      <InputGroup className="overflow-hidden">{children}</InputGroup>
    </form>
  );
};

